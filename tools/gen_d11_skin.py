"""Builds the D11 skin: SVG sheets and skin.toml, from the bitmaps of d11amp's default theme.

    python3 -I -B tools/gen_d11_skin.py OUT_DIR [--psz FILE]

The main window also has a bar view, a strip across the screen put
together from the same sheets, which the user switches to in the main menu.

The theme is flat pixel art, so every area of one colour becomes one whole
shape: a rectangle where it is one, an outline otherwise. An area is drawn
without its holes and what lies in a hole is drawn over it, so a window
frame with a panel in it is two rectangles, not a ring.
"""
import argparse
import colorsys
import io
import os
import zipfile

import numpy as np
from PIL import Image
from scipy import ndimage

TOOLS = os.path.dirname(os.path.abspath(__file__))
REFERENCE = os.path.join(TOOLS, "d11amp-default.wsz")

SHEETS = (
    "main", "cbuttons", "titlebar", "shufrep", "volume", "balance", "posbar", "text",
    "numbers", "monoster", "playpaus", "eqmain", "eq_ex", "pledit",
)  # fmt: skip

# The "D11 AMP" mark on the main window and the panel colour around it
MARK = (249, 89, 17, 16)
# The bolt of Popamp's logo, as an outline around its centre (118.8 units high)
BOLT = ((-10.43, -59.4), (23.46, -59.4), (0, -19.92), (30.91, -19.92), (-19.74, 59.4), (-3.72, 3.54), (-30.91, 3.54))

# A rectangle at least this wide and high is a shape of its own; smaller ones
# (dots, strokes of letters, rules) join their colour's path
PANEL = 3

# Colours this close are one colour that the drawing program saved unevenly
SAME_COLOUR = 2

META = """\
# D11: flat grey with orange lamps, after d11amp's default theme by Christian Ruesch.
# Generated by tools/gen_d11_skin.py; change the script, not this file.

[meta]
name = "Popamp D11"
author = "Christian Ruesch (vector port by Popamp)"
format_version = 1
"""


BODY, DISPLAY, LINE, COLON = "#50575a", "#20272a", "#000000", "#e0e7ea"
BAR_H = 20
# The bar's fixed ends, and the narrowest bar
BAR_LEFT, BAR_RIGHT, BAR_MIN = 316, 222, 640

BAR_WINDOW = """\

# --- the main window's bar view, from the sheets above ---

[[window]]
key = "main"

[window.bar]
edge = "bottom"
size = [%d, %d]
""" % (BAR_MIN, BAR_H)


# Colour sets. The theme is a family of blue-tinted greys with orange lamps.
# A set keeps the lamps and gives the greys another hue: (name, hue in
# degrees, saturation added). Blue is the orange's opposite on the colour
# wheel, brown is its neighbour.
FIRST_SET = "Graphite"
OTHER_SETS = (("Ocean", 208, 0.3), ("Cocoa", 24, 0.2))
# The greys are the colours about this hue and no more saturated than this
GREY_HUE, GREY_SATURATION = (185, 210), 0.2
# The greys met so far, as name by colour
GREYS = {}


def hexc(rgb):
    return "#%02x%02x%02x" % tuple(int(v) for v in rgb)


def hls(colour):
    return colorsys.rgb_to_hls(*(int(colour[i : i + 2], 16) / 255 for i in (1, 3, 5)))


def grey_name(colour):
    """The name a grey of the theme has in the colour sets, None for any other colour."""
    h, l, s = hls(colour)
    if not (GREY_HUE[0] <= h * 360 <= GREY_HUE[1] and s <= GREY_SATURATION):
        return None
    name = GREYS.setdefault(colour, f"tone-{round(l * 1000)}")
    assert sum(n == name for n in GREYS.values()) == 1, f"two greys are both {name}"
    return name


def paint(colour, attr="fill"):
    """The attributes that colour a shape: the colour, and its class if a colour set can change it."""
    name = grey_name(colour)
    suffix = "" if attr == "fill" else f"-{attr}"
    return (f'class="{name}{suffix}" ' if name else "") + f'{attr}="{colour}"'


def named(colour):
    """A colour for skin.toml: its name if a colour set can change it."""
    return grey_name(colour) or colour


def colour_sets():
    """The [colors] tables: the first set as the theme is, the others with the greys in their hue."""
    greys = sorted(GREYS.items(), key=lambda g: hls(g[0])[1])
    lines = [f"[colors.{FIRST_SET}]", *(f'{name} = "{colour}"' for colour, name in greys)]
    for set_name, hue, saturation in OTHER_SETS:
        lines += ["", f"[colors.{set_name}]"]
        for colour, name in greys:
            _, l, s = hls(colour)
            rgb = colorsys.hls_to_rgb(hue / 360, l, min(1, s + saturation))
            lines.append(f'{name} = "{hexc(round(v * 255) for v in rgb)}"')
    return lines + [""]


def read_reference(path):
    """The theme's files by lower-case name: bitmaps as RGB arrays, texts as strings."""
    files = {}
    with zipfile.ZipFile(path) as z:
        for name in z.namelist():
            stem, ext = os.path.splitext(name.lower())
            data = z.read(name)
            if ext == ".bmp":
                files[stem] = np.array(Image.open(io.BytesIO(data)).convert("RGB"))
            elif ext == ".txt":
                files[name.lower()] = data.decode("latin-1")
    return files


def merge_near_colours(images):
    """Replaces each rare colour that has a near twin by the twin, in every image."""
    counts = {}
    for img in images.values():
        colours, n = np.unique(img.reshape(-1, 3), axis=0, return_counts=True)
        for c, k in zip(map(tuple, colours.tolist()), n.tolist()):
            counts[c] = counts.get(c, 0) + k
    by_use = sorted(counts, key=counts.get, reverse=True)
    kept, twin = [], {}
    for c in by_use:
        near = next((k for k in kept if max(abs(a - b) for a, b in zip(c, k)) <= SAME_COLOUR), None)
        if near is None:
            kept.append(c)
        else:
            twin[c] = near
    for img in images.values():
        for c, k in twin.items():
            img[(img == c).all(axis=2)] = k


def areas(img):
    """Every connected area of one colour as (depth, colour, x, y, mask without holes), outermost first."""
    found = []
    depth = np.zeros(img.shape[:2], dtype=int)
    for colour in np.unique(img.reshape(-1, 3), axis=0):
        labels, n = ndimage.label((img == colour).all(axis=2))
        for i, box in enumerate(ndimage.find_objects(labels), 1):
            # a hole is what the outside cannot reach even across a corner
            solid = ndimage.binary_fill_holes(labels[box] == i, structure=np.ones((3, 3)))
            depth[box] += solid
            found.append((tuple(colour.tolist()), box, solid))
    out = []
    for colour, box, solid in found:
        ys, xs = np.nonzero(solid)
        # every area is inside itself, so the outermost ones count 1
        d = depth[box][ys[0], xs[0]] - 1
        out.append((d, colour, box[1].start, box[0].start, solid))
    out.sort(key=lambda a: (a[0], a[1], a[3], a[2]))
    return out


def border_edges(mask):
    """The unit edges around a mask with the area on their right, as end corners by start corner."""
    h, w = mask.shape
    m = np.zeros((h + 2, w + 2), dtype=bool)
    m[1:-1, 1:-1] = mask
    edges = {}
    for y, x in zip(*np.nonzero(m)):
        sides = (
            (m[y - 1, x], (x, y), (x + 1, y)),
            (m[y, x + 1], (x + 1, y), (x + 1, y + 1)),
            (m[y + 1, x], (x + 1, y + 1), (x, y + 1)),
            (m[y, x - 1], (x, y + 1), (x, y)),
        )
        for inside, start, end in sides:
            if not inside:
                edges.setdefault(start, []).append(end)
    return edges


def take_loop(edges):
    """Takes one closed loop out of the edges and returns its corners."""
    start = next(iter(edges))
    loop, at = [start], start
    while True:
        ends = edges[at]
        at = ends.pop()
        if not ends:
            del edges[loop[-1]]
        if at == start:
            break
        loop.append(at)
    return [p for i, p in enumerate(loop) if (loop[i - 1][0] == p[0]) != (p[0] == loop[(i + 1) % len(loop)][0])]


def outline(mask, x0, y0):
    """The outline of a mask as SVG path data, corners only."""
    edges = border_edges(mask)
    d = []
    while edges:
        corners = take_loop(edges)
        px, py = corners[0]
        # the mask was padded by one pixel
        d.append(f"M{px - 1 + x0} {py - 1 + y0}")
        for qx, qy in corners[1:]:
            d.append(f"h{qx - px}" if qy == py else f"v{qy - py}")
            px, py = qx, qy
        d.append("z")
    return "".join(d)


def draw(img):
    """The SVG shapes of an image: per depth and colour, its panels and one path for the rest."""
    shapes, paths = [], {}
    for depth, colour, x, y, solid in areas(img):
        h, w = solid.shape
        if solid.all() and min(w, h) >= PANEL:
            shapes.append((depth, f'<rect x="{x}" y="{y}" width="{w}" height="{h}" {paint(hexc(colour))}/>'))
        else:
            paths.setdefault((depth, colour), []).append(outline(solid, x, y))
    for (depth, colour), d in paths.items():
        shapes.append((depth, f'<path d="{"".join(d)}" {paint(hexc(colour))}/>'))
    shapes.sort(key=lambda s: s[0])
    return [s for _, s in shapes]


def popamp_mark(img):
    """Takes the "D11 AMP" mark off the main window and returns Popamp's ring and bolt for its place."""
    x, y, w, h = MARK
    colour = hexc(img[y, x])
    img[y : y + h, x : x + w] = img[y - 1, x - 1]
    cx, cy, r = x + w / 2, y + h / 2, h / 2 - 0.5
    k = (h - 5) / 118.8
    bolt = " ".join(f"{cx + px * k:.2f},{cy + py * k:.2f}" for px, py in BOLT)
    return [
        f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" {paint(colour, "stroke")}/>',
        f'<polygon points="{bolt}" {paint(colour)}/>',
    ]


def svg(img, extra=()):
    h, w = img.shape[:2]
    body = "\n".join([*draw(img), *extra])
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">\n{body}\n</svg>\n'


def playlist_colours(pledit_txt):
    keys = {"normal": "normal", "current": "current", "normalbg": "normal_bg", "selectedbg": "selected_bg"}
    lines = ["[playlist]"]
    for line in pledit_txt.splitlines():
        key, _, value = line.partition("=")
        if key.strip().lower() in keys:
            lines.append(f'{keys[key.strip().lower()]} = "{named(value.strip().lower())}"')
    return lines


def vis_colours(viscolor_txt):
    colours = []
    for line in viscolor_txt.splitlines()[:24]:
        colours.append(named(hexc(line.split("//")[0].split(",")[:3])))
    lines = ["[vis]", "colors = ["]
    lines += ["    " + ", ".join(f'"{c}"' for c in colours[i : i + 8]) + "," for i in range(0, 24, 8)]
    return lines + ["]"]


def rects(w, h, *shapes):
    """An SVG of rectangles given as (x, y, width, height, colour)."""
    body = "\n".join(f'<rect x="{x}" y="{y}" width="{rw}" height="{rh}" {paint(c)}/>' for x, y, rw, rh, c in shapes)
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">\n{body}\n</svg>\n'


